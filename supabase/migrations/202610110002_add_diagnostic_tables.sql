-- 1. diagnostic_sessions
create table if not exists public.diagnostic_sessions (
  id uuid primary key default gen_random_uuid(),

  learner_id uuid references public.learners(id) on delete cascade,

  status text not null default 'in_progress',

  total_questions integer not null default 20,
  correct_count integer,
  accuracy numeric(5,2),

  estimated_score integer,

  started_at timestamptz not null default now(),
  completed_at timestamptz,

  created_at timestamptz not null default now(),

  constraint diagnostic_sessions_status_check
    check (status in ('in_progress', 'completed'))
);


-- 2. question_attempts
create table if not exists public.question_attempts (
  id bigint generated by default as identity primary key,

  learner_id uuid references public.learners(id) on delete cascade,

  diagnostic_session_id uuid
    references public.diagnostic_sessions(id)
    on delete cascade,

  question_id text not null
    references public.questions(id)
    on delete cascade,

  subtype_id text
    references public.subtypes(id)
    on delete set null,

  selected_choice text not null,

  is_correct boolean not null,

  trap_id text
    references public.traps(id)
    on delete set null,

  answered_at timestamptz not null default now(),

  constraint question_attempts_choice_check
    check (selected_choice in ('A', 'B', 'C', 'D'))
);