-- 1. learners
create table if not exists public.learners (
  id uuid primary key default gen_random_uuid(),

  auth_user_id uuid unique references auth.users(id) on delete set null,

  name text not null,
  age integer,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);


-- 2. types
create table if not exists public.types (
  id text primary key,

  name text not null,
  description text,

  created_at timestamptz not null default now()
);


-- 3. subtypes
create table if not exists public.subtypes (
  id text primary key,

  type_id text not null references public.types(id) on delete cascade,

  name text not null,
  description text,

  created_at timestamptz not null default now()
);


-- 4. traps
create table if not exists public.traps (
  id text primary key,

  name text not null,
  description text,

  created_at timestamptz not null default now()
);


-- 5. questions
create table if not exists public.questions (
  id text primary key,

  subtype_id text references public.subtypes(id) on delete set null,

  question_type text not null,
  part text,
  difficulty text,

  stem text not null,
  explanation text,

  created_at timestamptz not null default now()
);


-- 6. question_choices
create table if not exists public.question_choices (
  id bigint generated by default as identity primary key,

  question_id text not null references public.questions(id) on delete cascade,

  choice_label text not null,
  choice_text text not null,

  is_correct boolean not null default false,

  trap_id text references public.traps(id) on delete set null,

  created_at timestamptz not null default now(),

  constraint question_choices_label_check
    check (choice_label in ('A', 'B', 'C', 'D')),

  constraint question_choices_question_label_unique
    unique (question_id, choice_label)
);