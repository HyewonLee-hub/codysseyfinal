create table if not exists public.vocabulary_quiz_sessions (
  id uuid primary key default gen_random_uuid(),

  learner_id uuid not null
    references public.learners(id)
    on delete cascade,

  status text not null default 'in_progress',

  started_at timestamptz not null default now(),
  completed_at timestamptz,
  created_at timestamptz not null default now(),

  constraint vocabulary_quiz_sessions_status_check
    check (status in ('in_progress', 'completed'))
);


create table if not exists public.vocabulary_quiz_items (
  id bigint generated by default as identity primary key,

  session_id uuid not null
    references public.vocabulary_quiz_sessions(id)
    on delete cascade,

  word_id uuid not null
    references public.vocabulary_words(id)
    on delete cascade,

  position integer not null,
  correct_meaning text not null,
  choices jsonb not null,
  created_at timestamptz not null default now(),

  constraint vocabulary_quiz_items_session_word_unique
    unique (session_id, word_id),

  constraint vocabulary_quiz_items_session_position_unique
    unique (session_id, position),

  constraint vocabulary_quiz_items_position_check
    check (position >= 1),

  constraint vocabulary_quiz_items_choices_array_check
    check (jsonb_typeof(choices) = 'array')
);


create table if not exists public.vocabulary_quiz_attempts (
  id bigint generated by default as identity primary key,

  session_id uuid not null
    references public.vocabulary_quiz_sessions(id)
    on delete cascade,

  word_id uuid not null
    references public.vocabulary_words(id)
    on delete cascade,

  selected_meaning text not null,
  is_correct boolean not null,
  answered_at timestamptz not null default now(),

  constraint vocabulary_quiz_attempts_session_word_unique
    unique (session_id, word_id)
);
