-- Shared vocabulary source records.
create table if not exists public.vocabulary_words (
  id uuid primary key default gen_random_uuid(),

  word text not null,
  meaning text not null,
  example text,
  difficulty text,

  created_at timestamptz not null default now(),

  constraint vocabulary_words_word_not_blank_check
    check (btrim(word) <> ''),

  constraint vocabulary_words_meaning_not_blank_check
    check (btrim(meaning) <> '')
);

create unique index if not exists vocabulary_words_lower_word_unique
  on public.vocabulary_words (lower(word));


-- Per-learner state for a shared vocabulary word.
create table if not exists public.learner_words (
  id bigint generated by default as identity primary key,

  learner_id uuid not null
    references public.learners(id)
    on delete cascade,

  word_id uuid not null
    references public.vocabulary_words(id)
    on delete cascade,

  is_saved boolean not null default false,
  is_memorized boolean not null default false,

  saved_at timestamptz,
  memorized_at timestamptz,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint learner_words_learner_word_unique
    unique (learner_id, word_id)
);


-- Fixed word assignments for one learner on one calendar day.
create table if not exists public.daily_word_assignments (
  id bigint generated by default as identity primary key,

  learner_id uuid not null
    references public.learners(id)
    on delete cascade,

  word_id uuid not null
    references public.vocabulary_words(id)
    on delete cascade,

  assigned_date date not null,
  created_at timestamptz not null default now(),

  constraint daily_word_assignments_learner_word_date_unique
    unique (learner_id, word_id, assigned_date)
);
