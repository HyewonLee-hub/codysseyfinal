create table if not exists public.learning_session_questions (
  id bigint generated by default as identity primary key,

  learning_session_id uuid not null
    references public.learning_sessions(id)
    on delete cascade,

  question_id text not null
    references public.questions(id)
    on delete cascade,

  position integer not null,

  created_at timestamptz not null default now(),

  constraint learning_session_questions_session_question_unique
    unique (learning_session_id, question_id),

  constraint learning_session_questions_session_position_unique
    unique (learning_session_id, position),

  constraint learning_session_questions_position_check
    check (position >= 1)
);
